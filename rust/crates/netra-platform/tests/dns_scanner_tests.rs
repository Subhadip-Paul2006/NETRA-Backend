#[test]
fn test_distinct_state_representation() {
    // 1. Available with DNS servers
    let available_with_servers = Observation::new(
        DeviceId::new(),
        "scanner.dns.v1",
        ObservationType::Dns,
        TargetDescriptor::Host {
            hostname: "test-host".to_string(),
        },
        5,
        PrivilegeStatus::Available,
        ConfidenceScore::KERNEL_AUTHORITATIVE,
        SensitivityLevel::Internal,
        ObservationPayload::Dns(DnsObservationPayload {
            dns_servers: vec![DnsServerRecord {
                server_address: "192.168.1.1".to_string(),
                interface_name: Some("Ethernet".to_string()),
                is_ipv6: false,
                classification: IpClassification::Private,
            }],
            search_domains: vec!["lan".to_string()],
            is_dynamic_dns_enabled: None,
        }),
    )
    .unwrap();

    // 2. Available but empty (e.g. host with static IP and no DNS configured)
    let available_empty = Observation::new(
        DeviceId::new(),
        "scanner.dns.v1",
        ObservationType::Dns,
        TargetDescriptor::Host {
            hostname: "isolated-host".to_string(),
        },
        2,
        PrivilegeStatus::Available,
        ConfidenceScore::KERNEL_AUTHORITATIVE,
        SensitivityLevel::Internal,
        ObservationPayload::Dns(DnsObservationPayload {
            dns_servers: Vec::new(),
            search_domains: Vec::new(),
            is_dynamic_dns_enabled: None,
        }),
    )
    .unwrap();

    // 3. Explicit Unsupported (macOS stub)
    let unsupported = Observation::new(
        DeviceId::new(),
        "scanner.dns.v1",
        ObservationType::Dns,
        TargetDescriptor::Host {
            hostname: "mac-host".to_string(),
        },
        0,
        PrivilegeStatus::Unsupported,
        ConfidenceScore::HEURISTIC,
        SensitivityLevel::Internal,
        ObservationPayload::Dns(DnsObservationPayload::default()),
    )
    .unwrap();

    // Verify distinct states
    assert_eq!(
        available_with_servers.privilege_level,
        PrivilegeStatus::Available
    );
    assert_eq!(available_empty.privilege_level, PrivilegeStatus::Available);
    assert_eq!(unsupported.privilege_level, PrivilegeStatus::Unsupported);
    assert_eq!(unsupported.confidence, ConfidenceScore::HEURISTIC);

    if let ObservationPayload::Dns(p1) = available_with_servers.payload {
        assert_eq!(p1.dns_servers.len(), 1);
    }
    if let ObservationPayload::Dns(p2) = available_empty.payload {
        assert!(p2.dns_servers.is_empty());
    }
    if let ObservationPayload::Dns(p3) = unsupported.payload {
        assert!(p3.dns_servers.is_empty());
    }
}

#[test]
fn test_dns_server_ip_classification() {
    let test_cases = [
        ("127.0.0.1", IpClassification::Loopback),
        ("127.0.0.53", IpClassification::Loopback),
        ("::1", IpClassification::Loopback),
        ("192.168.1.1", IpClassification::Private),
        ("10.0.0.1", IpClassification::Private),
        ("172.16.0.1", IpClassification::Private),
        ("fc00::1", IpClassification::Private),
        ("8.8.8.8", IpClassification::PublicGlobal),
        ("1.1.1.1", IpClassification::PublicGlobal),
        ("2001:4860:4860::8888", IpClassification::PublicGlobal),
        ("169.254.1.1", IpClassification::LinkLocal),
        ("fe80::1", IpClassification::LinkLocal),
        ("100.64.0.1", IpClassification::CarrierGradeNat),
    ];

    for (ip_str, expected_class) in test_cases {
        let ip = IpAddr::from_str(ip_str).expect("Valid IP address");
        assert_eq!(
            IpClassification::classify(&ip),
            expected_class,
            "Classification mismatch for {}",
            ip_str
        );
    }
}

