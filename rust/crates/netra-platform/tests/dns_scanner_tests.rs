#[tokio::test]
async fn test_native_platform_dns_scanner_execution() {
    let device_id = DeviceId::new();
    let scanner = PlatformDnsScanner::new();

    assert_eq!(scanner.scanner_id(), "scanner.dns.v1");
    assert_eq!(scanner.domain(), ObservationType::Dns);

    let obs = scanner
        .scan(&device_id)
        .await
        .expect("Native DNS scan must not panic");

    assert_eq!(obs.schema_version, 1);
    assert_eq!(obs.device_id, device_id);
    assert_eq!(obs.scanner_id, "scanner.dns.v1");
    assert_eq!(obs.observation_type, ObservationType::Dns);
    assert_eq!(obs.sensitivity, SensitivityLevel::Internal);
    assert_eq!(obs.evidence_hash.len(), 64);
    assert!(
        obs.duration_ms < 5000,
        "Scan must complete within 5 seconds"
    );

    #[cfg(windows)]
    {
        assert_eq!(obs.privilege_level, PrivilegeStatus::Available);
        assert_eq!(obs.confidence, ConfidenceScore::KERNEL_AUTHORITATIVE);

        if let ObservationPayload::Dns(payload) = &obs.payload {
            for server in &payload.dns_servers {
                assert!(!server.server_address.is_empty());
                let parsed = IpAddr::from_str(&server.server_address).expect("Valid IP address");
                assert_eq!(server.is_ipv6, parsed.is_ipv6());
                assert_eq!(server.classification, IpClassification::classify(&parsed));
            }
        } else {
            panic!("Expected ObservationPayload::Dns");
        }
    }

    #[cfg(target_os = "macos")]
    {
        assert_eq!(obs.privilege_level, PrivilegeStatus::Unsupported);
        assert_eq!(obs.confidence, ConfidenceScore::HEURISTIC);
    }
}

#[test]
fn test_linux_resolv_conf_standard_parsing() {
    let fixture = r#"
# Dynamic resolv.conf(5) file for glibc resolver(3) generated by resolvconf(8)
#     DO NOT EDIT THIS FILE BY HAND -- YOUR CHANGES WILL BE OVERWRITTEN
nameserver 192.168.1.1
nameserver 8.8.8.8
nameserver 8.8.4.4
search corp.local example.com
options edns0 trust-ad
"#;

    let (servers, domains) = parse_resolv_conf(fixture);

    assert_eq!(servers.len(), 3);
    assert_eq!(servers[0].server_address, "192.168.1.1");
    assert!(!servers[0].is_ipv6);
    assert_eq!(servers[0].classification, IpClassification::Private);

    assert_eq!(servers[1].server_address, "8.8.8.8");
    assert!(!servers[1].is_ipv6);
    assert_eq!(servers[1].classification, IpClassification::PublicGlobal);

    assert_eq!(servers[2].server_address, "8.8.4.4");
    assert!(!servers[2].is_ipv6);
    assert_eq!(servers[2].classification, IpClassification::PublicGlobal);

    assert_eq!(domains.len(), 2);
    assert_eq!(domains[0], "corp.local");
    assert_eq!(domains[1], "example.com");
}

#[test]
fn test_linux_resolv_conf_ipv6_and_scoped_link_local() {
    let fixture = r#"
; IPv6 DNS nameservers
nameserver 2001:4860:4860::8888
nameserver fe80::1%eth0
search subnet.v6.local
"#;

    let (servers, domains) = parse_resolv_conf(fixture);

    assert_eq!(servers.len(), 2);

    assert_eq!(servers[0].server_address, "2001:4860:4860::8888");
    assert!(servers[0].is_ipv6);
    assert_eq!(servers[0].interface_name, None);
    assert_eq!(servers[0].classification, IpClassification::PublicGlobal);

    assert_eq!(servers[1].server_address, "fe80::1");
    assert!(servers[1].is_ipv6);
    assert_eq!(servers[1].interface_name, Some("eth0".to_string()));
    assert_eq!(servers[1].classification, IpClassification::LinkLocal);

    assert_eq!(domains, vec!["subnet.v6.local"]);
}

