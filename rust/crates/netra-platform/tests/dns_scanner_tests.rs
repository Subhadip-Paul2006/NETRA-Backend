#[test]
fn test_windows_dns_suffix_aggregation_semantics() {
    // Tests that search_domains correctly preserves unique adapter suffixes
    let mut search_domains: Vec<String> = Vec::new();
    let adapter_suffixes = ["corp.local", "corp.local", "backup.lan", ""];

    for &suffix in &adapter_suffixes {
        let s = suffix.trim().to_string();
        if !s.is_empty() && !search_domains.contains(&s) {
            search_domains.push(s);
        }
    }

    assert_eq!(search_domains.len(), 2);
    assert_eq!(search_domains[0], "corp.local");
    assert_eq!(search_domains[1], "backup.lan");
}
